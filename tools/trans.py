# 文法：英文意思 | 英文注意事項 | 英文例句翻譯
G = r"""
1|After a long process, in the end… (usually badly)|The outcome is almost always negative; not used for momentary actions.|After talking it over for a long time, we still reached no conclusion.
2|So … that…, because of too much…|The result is usually unusual or unwanted; not for everyday trivia.|I was so happy that I ended up in tears.
3|Because of such extreme…|A noun goes in the middle, often an adjective nominalized with ～さ.|It's so hot that I don't feel like going outside.
4|Now that…, since…|Followed by obligation, resolve, a command or advice — not a plain fact.|Now that I've promised, I must keep my word.
5|On the one hand…, on the other…|The two clauses contrast; this is not cause and effect.|He is a strict teacher and at the same time a kind father.
6|While doing…, also…|Don't confuse it with 動詞辭書形＋一方だ, which means "more and more".|He works at a company while also attending graduate school.
7|Ever since…|Not for future events, and not for short spans of time.|I haven't been back home once since I came to Japan.
8|After doing A, then B|A is always a completed action, so it takes the た form.|I'll give you my answer after discussing it with my family.
9|In the course of…, when it comes to…|Usually followed by 必要だ, 大切だ, 欠かせない and the like.|Japanese is indispensable for living in Japan.
10|Now that…, since…|Stiffer and more written than ～以上は; followed by resolve or duty.|Now that I've taken it on, I'll see it through responsibly.
11|Can possibly… / cannot possibly…|Expresses possibility, not ability; the negative is always read えない.|That sort of thing is simply impossible.
12|On the occasion of…, when…|Polite and formal, common in letters; not used for unfortunate events.|When you come to Tokyo, do please drop by.
13|The effort paid off / was in vain|かいがあって takes a good result, かいもなく a wasted one.|My daily practice paid off and I won the tournament.
14|As far as…, within the limits of…|Set phrases: 私の知る限り, 見渡す限り, できる限り.|As far as I know, he isn't that kind of person.
15|As long as … continues|～ない限り means "unless…".|As long as I stay healthy, I want to keep working.
16|No sooner had… than…|The second clause takes no volitional, imperative, request or negative form; the subject is usually a third person.|My son had barely got home before he went out to play again.
17|Just as…, before … had even finished|The same verb must appear on both sides; no volitional or imperative after it.|The bell had hardly rung before the students burst out of the classroom.
18|Might well… (something bad)|Only for negative or worrying outcomes; narrower and stronger than かもしれない.|If you drive like that, you could well cause an accident.
19|Cannot… (a polite refusal)|Common in business and service settings: わかりかねます, お答えしかねます.|I'm very sorry, but I'm not able to answer that.
20|As if…, as though…|Often paired with まるで; nouns take である＋かのようだ.|He talks as if he had seen it with his own eyes.
21|Judging from…, in terms of…|A person cannot come before it; use ～の立場から言うと for a standpoint.|From experience, this method is the best.
22|Judging from…, from the standpoint of…|Unlike から言うと, a person can come before it; からして also means "even just…".|Judging by the look of it, the exam went well.
23|Just because…, it doesn't mean…|The second clause is negative or partly so, often with わけではない or とは限らない.|Just because it's cheap doesn't mean you should buy too much.
24|Worth doing, rewarding|Attaches to a limited set of verbs; ～がいがない means "not worth it".|This job is rewarding.
25|Hard to bring oneself to…|Written style; used with mental verbs, not physical difficulty.|His story is hard to believe.
26|Haven't … ever since|The second clause must be negative.|I saw him last year and haven't heard from him since.
27|Only, just; stuck in one state|寝たきり (bedridden) is a common exam item; spoken Japanese often uses ～っきり.|My mother is bedridden.
28|A touch of…, slightly…|Almost always for unwanted tendencies: 風邪気味, 疲れ気味, 遅れ気味.|I'm coming down with a cold, so I'll head home early.
29|Even though…, and yet…|Carries blame or contempt; both clauses share a subject; never used about yourself.|You know perfectly well, and yet you won't tell me.
30|Rather than…, I'd sooner…|Often followed by ほうがましだ or ほうがいい.|Rather than quit halfway, it's better not to start at all.
31|Looking…, seeming…|Describes how someone else appears, not yourself; ありげ and なさげ also occur.|The child has a lonely look on his face.
32|You should…, the thing to do is…|Not appropriate towards superiors; distinct from the exclamatory ～ことだ.|If you want to get good, you should practice every day.
33|Since…, seeing as…|Conversational; gives one of several reasons, usually before a suggestion.|The rain has stopped, so let's head out.
34|How very…!|Almost always preceded by どんなに, なんと or どれほど.|How long I have waited for this day!
35|Without …ing|Written style, the formal equivalent of ～ないで.|He kept working without taking a single day off.
36|To one's…, …ly enough|Only with words of emotion or evaluation; the second clause is an established fact.|To my surprise, he passed the exam.
37|When it comes to…|A noun takes ～のことになると.|Once baseball comes up, he never stops talking.
38|Have no choice but to…|Written style; する becomes せざるを得ない.|Because of the typhoon, we had no choice but to cancel the trip.
39|From the standpoint of…, in terms of…|Attaches to Sino-Japanese nouns: 教育, 法律, 健康, 仕事, 経験, 歴史.|Educationally speaking, this program isn't fit for children.
40|As soon as…|The second clause can't be past tense or refer to something already done; it states intention or a request.|I'll contact you as soon as the meeting ends.
41|Depends on…|Only nouns come before it — don't confuse it with the ます形＋次第 pattern.|The result depends on your own effort.
42|After…, finally…|Unlike あげく the result is neutral or positive; the first part must involve a process.|After a long discussion, we finally reached a conclusion.
43|Ended up never …ing|Carries regret; する becomes せずじまい.|I was so busy that I never got to see him.
44|Can't help …ing|する becomes せずにはいられない; the subject is normally the speaker.|I can't watch that film without crying.
45|Doesn't look like it will…|A stronger denial than ～そうじゃない.|With this much to do, it doesn't look like I'll finish today.
46|Freshly…, just …ed|Only a few verbs take it: 焼き, 炊き, とれ, でき, 塗り, 生まれ, 入り.|Freshly baked bread is delicious.
47|Simply can't be…|Appears as ～て＋（ら）れた＋ものではない and carries strong criticism.|This dish is so bad it's inedible.
48|As one would expect from…|A positive evaluation; not used about yourself.|As you'd expect after ten years in Japan, his Japanese is excellent.
49|At least…; it could be worse|A grudging acceptance, usually after が or けど.|The pay is low, but at least I have a job.
50|There's no way…|Casual; for people you're close to, not for formal settings.|There's no way I can work out a problem that hard.
51|While …ing|Written style, more formal than ながら; both clauses share a subject.|I wrote the report while listening to music.
52|Even though…, and yet…|Adding も makes the contrast explicit; common with 思いつつ and 知りつつ.|I know it's bad for me, and yet I can't quit smoking.
53|Is gradually …ing|Used with verbs of change; stresses the process more than ～ている.|The economy is gradually recovering.
54|Leave … on or undone; keep …ing|Carries blame when something is left unattended; otherwise just continuation.|I went out and left the lights on.
55|Tend to…, easily…|Usually a negative trait: 忘れっぽい, 怒りっぽい, 飽きっぽい.|I've become forgetful lately.
56|-ish, like…|Attaches to nouns to say something leans that way: 水っぽい, 子供っぽい, 男っぽい.|This soup is watery and has no taste.
57|-ish (colour or overall impression)|Conjugates like an い-adjective: っぽくない, っぽかった.|She was wearing blackish clothes.
58|Ever since…|More written and emphatic than ～以来; often followed by 一度も～ない.|I haven't been late once since I started this job.
59|Even if it means…|The first part is an extreme measure, the second a strong will or wish.|I want to study abroad even if I have to borrow money.
60|Can't help feeling…, terribly…|Only for feelings and sensations; the subject is the speaker.|I can't stop worrying about the exam results.
61|Can't afford to keep …ing|Spoken as ～ちゃいられない; shows resolve or urgency.|I have an exam tomorrow, so I can't keep playing around.
62|Even going so far as to…|Implies the speaker finds it excessive; verbs take てまで, nouns までして.|There's no need to work to the point of ruining your health.
63|Show someone by actually doing it|The literal use; the subject is the one demonstrating.|The teacher wrote it out in front of the students.
64|I'll do it — just watch me|Often with 今度こそ, 必ず or 絶対; the subject is the speaker.|This time I'll pass for sure, just watch.
65|It's not necessarily the case that…|Usually follows a ～ば or ～たら conditional.|Expensive doesn't necessarily mean good.
66|…and the like, such as…|A noun must follow; the usual shape is AやBといった＋noun.|I like sports such as soccer and baseball.
67|Speaking of…, it really is…|Followed by exaggerated expressions like ない or 言葉にできない.|The beauty of Mt. Fuji is beyond words.
68|When you say A, it has to be B|A topic-marking use; B is the typical example everyone thinks of.|When it comes to Japanese flowers, it has to be cherry blossoms.
69|I hear that…, apparently…|Used when the source is vague or your memory is hazy.|I hear he's getting married next month.
70|Almost…, nearly…|Often with もう少しで or 危うく; takes the dictionary form, not た.|I very nearly missed the train.
71|Not a single…|Fixed shape: 一＋counter＋として＋negative.|I can't believe a single word he says.
72|Together with…; as…; both … and…|Three different uses — decide from the context.|As I get older, my stamina has declined.
73|If it comes to…, once…|Stronger than ～なら: it means "if it really turns out that way".|If I'm really going to study abroad, I'll need money.
74|① … means … ② To think that…!|In sense ②, 思わなかった or 驚いた is usually left unsaid.|I never thought he would fail the exam.
75|Far from…, let alone…|The second clause is usually more extreme, sometimes in the opposite direction.|Let alone kanji, he can't even read hiragana.
76|This is no time for…|Takes a noun or a dictionary-form verb; circumstances make it impossible.|I'm far too busy for a trip.
77|Unless…, … not|The second clause must be negative; close to ～なければ～ない.|Until I actually see it, I can't say anything.
78|It's not that I don't…|A vague, hedged way of half-agreeing.|I don't like it, but it's not that I won't eat it.
79|Get by without …ing|する becomes せずに済む; ～で済む means "… is enough".|A friend lent me one, so I didn't have to buy it.
80|It's not that I don't…, somewhat|Mostly with feelings and thoughts; more guarded than ないことはない.|I can sort of understand how he feels.
81|Not impossible, depending on…|Often paired with ～次第では or ～によっては.|Depending on the terms, I might well take it on.
82|You never know, it might…|A triple negative — translate with care; usually followed by から and a precaution.|It might well rain, so let's take an umbrella.
"""


def _load(block, n):
    d = {}
    for line in block.strip().split("\n"):
        line = line.strip()
        if not line:
            continue
        parts = line.split("|")
        assert len(parts) == n + 1, "欄位數不對：" + line
        d[int(parts[0])] = [p.strip() for p in parts[1:]]
    return d


